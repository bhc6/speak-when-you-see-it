"""Table 2 (ablation of the two kinds of paired negatives), generated from
audit_1114/RESULTS_AUTHORITATIVE.md, decision_decomp.json and epair_summary.json. Multi-seed rows are means over the listed runs.
Run: python3 make_tables.py  (writes tab/tab2_ablation.tex)"""
import json, os, re, statistics as st
ROOT = "DATA_ROOT"; A = f"{ROOT}/audit_1114"; HERE = os.path.dirname(os.path.abspath(__file__))
R = {}
for l in open(f"{A}/RESULTS_AUTHORITATIVE.md"):
    c = [x.strip() for x in l.split("|")]
    if len(c) > 8 and c[1] in ("qicd", "mc"): R[(c[1], c[2].split("/")[-1])] = (float(c[3]), float(c[6]), float(c[8]) if c[8] else None)
D = json.load(open(f"{A}/decision_decomp.json")); E = json.load(open(f"{A}/epair_summary.json"))
# pre-registered extra seeds of "+ notdone" (QICD test36 + evidence pairs only; no Ego-MC, no decision decomposition by design)
ADD = json.load(open(f"{HERE}/data_addendum_1116.json"))
for k in ("ABL_noCL_s2", "ABL_noCL_s3"):
    R[("qicd", k)] = (ADD[k]["qicd_ic"], ADD[k]["qicd_f1"], ADD[k]["qicd_margin"]); E[k] = {"mis_pairacc": ADD[k]["mis_pairacc"]}
m = lambda v: sum(v) / len(v)
pc = lambda x: str(int(x + 0.5 + 1e-9))   # integer percent, half up (34.5 -> 35, as in the text); f"{x:.0f}" rounds half to even
# name, QICD runs, Ego-MC runs, decision-decomposition keys, evidence-pair keys
ROWS = [
 ("Plain fine-tuning$^{\\ddagger}$", ["T1_round1_test36"], ["T1_mc"], ["T1plain"], []),
 ("No neg., re-balanced sampling", ["T1v2_2400_greedy_test36"], ["T1v2_2400_greedy_mc"], ["T1v2"], ["T1v2"]),
 ("No paired neg.", ["ABL_none_greedy_test36", "ABL_none_s1_greedy_test36"], ["ABL_none_greedy_mc", "ABL_none_s1_greedy_mc"], ["none_s0", "none_s1"], ["ABL_none", "ABL_none_s1"]),
 ("+ notdone$^{*}$", ["ABL_noCL_greedy_test36", "ABL_noCL_s1_greedy_test36", "ABL_noCL_s2", "ABL_noCL_s3"], ["ABL_noCL_greedy_mc", "ABL_noCL_s1_greedy_mc"], ["noCL_s0", "noCL_s1", "noCL_s2", "noCL_s3"], ["ABL_noCL", "ABL_noCL_s1", "ABL_noCL_s2", "ABL_noCL_s3"]),
 ("+ clean", ["ABL_noND_greedy_test36", "ABL_noND_s1_greedy_test36"], ["ABL_noND_greedy_mc", "ABL_noND_s1_greedy_mc"], ["noND_s0", "noND_s1"], ["ABL_noND", "ABL_noND_s1"]),
 ("\\textbf{ECT} (both)", ["sft_greedy_test36", "s1_greedy_test36", "s2_greedy_test36", "s3_greedy_test36"], ["sft_greedy_mc", "s1_greedy_mc", "s2_greedy_mc", "s3_greedy_mc"],
  ["ECT_s0", "ECT_s1", "ECT_s2", "ECT_s3"], ["T1v4_s0", "T1v4_s1", "T1v4_s2", "T1v4_s3"]),
]
UNM = [k for k in ("ECT_unm_s0", "ECT_unm_s1") if k in ADD]     # random-moment negatives: added to the table once both seeds are finished
for k in UNM: R[("qicd", k)] = (ADD[k]["qicd_ic"], ADD[k]["qicd_f1"], ADD[k]["qicd_margin"]); E[k] = {"mis_pairacc": ADD[k].get("mis_pairacc", float("nan"))}
EXTRA = [("Random-moment neg.$^{\\S}$", UNM)] if len(UNM) == 2 else []
out = []
for name, q, mc, dk, ek in ROWS:
    qi, qf = m([R[("qicd", k)][0] for k in q]), m([R[("qicd", k)][1] for k in q]); mi, mf = m([R[("mc", k)][0] for k in mc]), m([R[("mc", k)][1] for k in mc])
    qd, md = m([R[("qicd", k)][2] for k in q]), m([R[("mc", k)][2] for k in mc])   # mean margin over the frontier
    sg = lambda v: f"${v:+.3f}$".replace("+0.000", "0.000").replace("-0.000", "0.000")
    vo = m([D["qicd"][k]["voided by false alarm"] for k in dk]); ea = m([D["qicd"][k]["confirmed too early"] for k in dk])
    pa = f"{m([E[k]['mis_pairacc'] for k in ek]):.2f}" if ek else "--"
    b = lambda s: s   # no bold numbers: ECT is not the best cell of every column; its row is shaded instead
    if "ECT" in name: out.append("    \\rowcolor{ectorange!16}")
    out.append(f"    {name} & {len(q)} & {b(f'{qi:.1f}')} & {b(f'{qf:.3f}')} & {sg(qd)} & {b(f'{mi:.1f}')} & {b(f'{mf:.3f}')} & {sg(md)} & {pc(vo)} & {pc(ea)} & {b(pa)} \\\\")
    if "ECT" in name:
        for xn, xk in EXTRA:
            out.append(f"    {xn} & {len(xk)} & {m([R[('qicd', k)][0] for k in xk]):.1f} & {m([R[('qicd', k)][1] for k in xk]):.3f} & {sg(m([R[('qicd', k)][2] for k in xk]))} & -- & -- & -- & {pc(m([D['qicd'][k.replace('ECT_','')]['voided by false alarm'] for k in xk]))} & {pc(m([D['qicd'][k.replace('ECT_','')]['confirmed too early'] for k in xk]))} & {m([E[k]['mis_pairacc'] for k in xk]):.2f} \\\\")
    if name.startswith("No neg., re-"): out.append("    \\midrule")
    print(name, len(q), "margins", round(qd, 3), round(md, 3), "|", round(qi, 1), round(qf, 3), round(mi, 1), round(mf, 3), round(vo, 1), round(ea, 1), pa)
tex = r"""% Table 2 -- generated by make_tables.py from audit_1114/; do not edit. Multi-seed rows are means over the seeds (column n).
\begin{table*}[t]
  \centering
  \small
  \setlength{\tabcolsep}{6.5pt}
  \begin{tabular}{@{}lccccccccccc@{}}
    \toprule
    & & \multicolumn{3}{c}{QICD} & \multicolumn{3}{c}{Ego-MC-Bench} & \multicolumn{3}{c}{QICD, mechanism} \\
    \cmidrule(lr){3-5}\cmidrule(lr){6-8}\cmidrule(l){9-11}
    Training & $n$ & IC-Acc $\uparrow$ & F1 $\uparrow$ & $\Delta$ & IC-Acc $\uparrow$ & F1 $\uparrow$ & $\Delta$ & Void $\downarrow$ & Early $\downarrow$ & Pair $\uparrow$ \\
    \midrule
""" + "\n".join(out) + r"""
    \bottomrule
  \end{tabular}
  \caption{\textbf{What each ingredient changes.}
  All rows fine-tune Qwen3-VL-2B and use greedy decoding; means over $n$ training seeds. $\Delta$: margin over the video-blind frontier. Void / Early: share (\%) of mistake-free steps voided by a false alarm / confirmed too early. Pair: accuracy on time-matched mistake pairs (0.50 for every clock-only policy).
  ECT is to be compared with ``No paired neg.'', which differs from it in the negatives alone.
  $^{*}$Two seeds on Ego-MC-Bench. $^{\ddagger}$An earlier recipe that also differs in how situations are placed and sampled (supplement~J); it never raises an alarm.UNMNOTE}
  \label{tab:ablation}
\end{table*}
"""
tex = tex.replace("UNMNOTE", r" $^{\S}$ECT with its negatives drawn at random moments of the same steps (QICD only)." if EXTRA else "")
os.makedirs(f"{HERE}/tab", exist_ok=True); open(f"{HERE}/tab/tab2_ablation.tex", "w").write(tex)

