"""Supplement B, stronger learned blind policy (post-hoc analysis, added after the results; not pre-registered).
Reads analysis_code/blind_strong/out/summary_strong.json (summarize_strong.py) and verify_strong*.json, writes
supp/tab_blindstrong.tex and supp/blindstrong_numbers.json (source of record for num_check.py).
Run: python3 make_supp_blindstrong.py"""
import json, os
ROOT = "DATA_ROOT"; HERE = os.path.dirname(os.path.abspath(__file__)); B = f"{ROOT}/analysis_code/blind_strong/out"
S = json.load(open(f"{B}/summary_strong.json")); E = S["ect"]
def margin(value):
    signed = f"{value:+.3f}"
    return rf"\boldmath${signed}$" if value < 0 else f"${signed}$"


SETS = [("qicd", "QICD Adv.\\ Planning"), ("main", "QICD Main"), ("mc", "Ego-MC-Bench")]
lines = []
for dataset_index, (dataset, name) in enumerate(SETS):
    if dataset_index:
        lines.append(r"    \midrule")
    for decoding, label in (("greedy", "Greedy"), ("thr", "Thresholded")):
        if decoding == "thr":
            lines.append(r"    \addlinespace[2pt]")
        for seed in range(4):
            result = E[f"{dataset}/{decoding}/s{seed}"]
            test_set = name if decoding == "greedy" and seed == 0 else ""
            decoding_text = label if seed == 0 else ""
            values = [margin(result[key]) for key in ("paper", "strict", "full", "oos_full")]
            cells = [test_set, decoding_text, str(seed), *values, f"{result['p_full']:.3f}"]
            lines.append("    " + " & ".join(cells) + r" \\")
tab = r"""% generated by make_supp_blindstrong.py -- do not edit
\begin{table*}[t]
  \centering\small\setlength{\tabcolsep}{4pt}
  \begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}llcccccc@{}}
    \toprule
    & & & \multicolumn{3}{c}{Tuned on the whole test set} & \multicolumn{2}{c}{Held out (500 half splits)} \\
    \cmidrule(lr){4-6}\cmidrule(l){7-8}
    Test set & Decoding & Seed & Rules (paper) & \shortstack{+ learned\\paper's inputs} & \shortstack{+ learned\\all inputs} & \shortstack{Margin\\all inputs} & $P(\mathrm{margin}>0)$ \\
    \midrule
""" + "\n".join(lines) + r"""
    \bottomrule
  \end{tabular*}
  \caption{\textbf{Margins of ECT against a stronger, learned video-blind policy} (post-hoc analysis). Bold margins fall inside the frontier.
  ``Rules (paper)'': the frontier of the paper. ``+ learned'': the upper hull of that frontier and of 18,900 learned blind policies, all tuned on the test set; ``paper's inputs'': instruction text, step index, elapsed time and training priors; ``all inputs'': in addition the position in the plan and the observed durations of the earlier steps of the recording.
  Held out: the blind policies on the hull of one half of the test recordings are scored on the other half, together with ECT; this frontier has no per-step mixtures.}
  \label{tab:blindstrong}
\end{table*}
"""
open(f"{HERE}/supp/tab_blindstrong.tex", "w").write(tab)
# numbers quoted in the text
V = {"qicd": json.load(open(f"{B}/verify_strong.json")), "main": json.load(open(f"{B}/verify_strong_main.json"))}
fam = {f"{s}/{f}": dict(f1_max=V["main" if s == "main" else "qicd"]["families"][f"{'qicd' if s == 'main' else s}/{f}"]["f1_max"],
                        ic_max=V["main" if s == "main" else "qicd"]["families"][f"{'qicd' if s == 'main' else s}/{f}"]["ic_max"])
       for s in ("qicd", "mc", "main") for f in ("rules", "strict", "full")}
O = S["others"]; inside = [r for r in O.values() if r["paper"] <= 0]; beyond = [r for r in O.values() if r["paper"] > 0]
N = dict(families=fam, ect=E, others=O, n_inside=len(inside), n_inside_still={f: sum(r[f] <= 0 for r in inside) for f in ("strict", "full")},
         n_beyond=len(beyond), n_beyond_still={f: sum(r[f] > 0 for r in beyond) for f in ("strict", "full")})
json.dump(N, open(f"{HERE}/supp/blindstrong_numbers.json", "w"), indent=1)
print({k: v for k, v in N.items() if k.startswith("n_")}); print(json.dumps(fam))
