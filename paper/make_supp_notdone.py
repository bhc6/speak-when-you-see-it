"""Supplement C, "What the notdone negatives change" (post-hoc, exploratory): long-step outcome table and one illustrative case.
Reads analysis_code/notdone_audit/out/{long_decomp,selfcheck,first_check,audit_cases}.json; writes supp/tab_notdone.tex,
supp/notdone_numbers.json (source of record for num_check.py) and fig/supp_notdone_case.pdf.
The case is chosen by a fixed rule among the audited Ego-MC-Bench steps on which ECT (>= 3 of 4 seeds) confirms on time and
"+ clean" (>= 1 of 2 seeds) confirms early: the instruction states no duration, and the step has the (lower) median duration.
Run: python3 make_supp_notdone.py"""
import json, os, re
import numpy as np
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from PIL import Image
ROOT = "DATA_ROOT"; HERE = os.path.dirname(os.path.abspath(__file__)); A = f"{ROOT}/analysis_code/notdone_audit/out"
LD, SC, FC = (json.load(open(f"{A}/{n}.json")) for n in ("long_decomp", "selfcheck", "first_check"))
G = ["ECT", "+ clean", "+ notdone", "no neg."]
def ci(x): return f"${x[0]:+.1f}$ [{x[1][0]:+.1f}, {x[1][1]:+.1f}]"
rows = []
for c, lab in (("on time", "On time"), ("early", "Early"), ("alarm", "Alarm raised")):
    for ds, name in (("mc", "Ego-MC-Bench"), ("qicd", "QICD")):
        lv = LD[ds]["levels"]
        rows.append(f"    {lab if ds == 'mc' else ''} & {name} ({LD[ds]['n']}) & " + " & ".join(f"{lv[g][c]:.1f}" for g in G) + f" & {ci(LD[ds]['diff'][c])} \\\\")
    if c != "alarm": rows.append("    \\midrule")
tab = r"""% generated by make_supp_notdone.py -- do not edit
\begin{table*}[t]
  \centering\small\setlength{\tabcolsep}{5pt}
  \resizebox{\ifdim\width>\linewidth\linewidth\else\width\fi}{!}{%
  \begin{tabular}{llccccc}
    \toprule
    Outcome (\%) & Long steps ($n$) & ECT & + clean & + notdone & No neg. & ECT $-$ + clean [95\% CI] \\
    \midrule
""" + "\n".join(rows) + r"""
    \bottomrule
  \end{tabular}}
  \caption{\textbf{Long mistake-free steps} (the longest third of the steps scored in every run: at least """ + f"{LD['mc']['cut']:.1f}" + r"""\,s on Ego-MC-Bench and """ + f"{LD['qicd']['cut']:.1f}" + r"""\,s on QICD), greedy decoding; mean over 4 seeds of ECT and 2 seeds of each variant; paired bootstrap over videos. Post-hoc, exploratory analysis.}
  \label{tab:notdone}
\end{table*}
"""
open(f"{HERE}/supp/tab_notdone.tex", "w").write(tab)
N = dict(long_decomp=LD, selfcheck={k: {kk: v for kk, v in SC[k].items() if kk != "until_only"} for k in SC}, first_check=FC)
json.dump(N, open(f"{HERE}/supp/notdone_numbers.json", "w"), indent=1)

# ---- the illustrative case
cases = json.load(open(f"{A}/audit_cases.json"))["cases"]
STRICT = re.compile(r"\b(minute|minutes|min|second|seconds|sec|hour|hours)\b", re.I)
pool = sorted([c for c in cases if c["tag"] == "F" and not STRICT.search(c["instr"])], key=lambda c: (c["dur"], c["video"], c["step"]))
c = pool[(len(pool) - 1) // 2]; i = cases.index(c)
FR = f"{A}/audit_frames"; ect_t = sorted({round(c["end"] + o - c["start"], 1) for o in c["ect_offsets"] if o is not None})
cl_t = [round(c["end"] + o - c["start"], 1) for o in c["clean_offsets"] if o is not None]
lab = ["step start", "stirring begins; '+ clean' confirms", "still stirring, lid off", "annotated end: lid on"]
fig = plt.figure(figsize=(7.0, 2.15)); fw = 0.245
for j in range(4):
    ax = fig.add_axes([0.005 + j * 0.249, 0.36, fw, 0.56]); im = Image.open(f"{FR}/{i:02d}_F_{c['video']}_s{c['step']}_{j}.jpg").convert("RGB")
    ax.imshow(np.asarray(im)); ax.set_axis_off(); ax.set_title(f"{c['times'][j] - c['start']:.0f} s: {lab[j]}", fontsize=6.3, pad=2)
ax = fig.add_axes([0.03, 0.17, 0.94, 0.11]); d = c["dur"]
ax.axvspan(d - 15, d + 15, color="#d9d8d3", lw=0); ax.axvline(d, color="#52514e", lw=.8)
ax.plot(cl_t, [0.72] * len(cl_t), "v", color="#52514e", ms=5, label="+ clean: confirmations of its 2 seeds"); ax.plot(ect_t, [0.28] * len(ect_t), "v", color="#eb6834", ms=5, label="ECT: all 4 seeds confirm here"); ax.set_ylim(0, 1)
ax.set_xlim(-2, d + 17); ax.set_yticks([]); ax.tick_params(labelsize=6); ax.set_xlabel("time since step start (s); gray: tolerance around the annotated end", fontsize=6, labelpad=1)
for s_ in ("top", "right", "left"): ax.spines[s_].set_visible(False)
ax.legend(fontsize=5.5, frameon=False, loc="upper left", bbox_to_anchor=(0.0, 2.05), ncol=2)
fig.savefig(f"{HERE}/fig/supp_notdone_case.pdf"); fig.savefig(f"{HERE}/fig/supp_notdone_case.png", dpi=170); plt.close(fig)
os.makedirs(f"{HERE}/fig/notdone_case", exist_ok=True)
for j in range(4): Image.open(f"{FR}/{i:02d}_F_{c['video']}_s{c['step']}_{j}.jpg").save(f"{HERE}/fig/notdone_case/f{j}.jpg")
json.dump(dict(case=c, ect_confirm_s=ect_t, clean_confirm_s=cl_t, rule=__doc__.split("\n")[3:5]), open(f"{HERE}/fig/notdone_case/meta.json", "w"), indent=1)
print("case", c["video"], c["step"], c["dur"], "ECT", ect_t, "+clean", cl_t)
