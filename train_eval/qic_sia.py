"""Official turn-based baseline with SIA scoring decisions (S2) and retrieved feedback (greedy LoRA model merged).
Same prompts, windows, call sequence and preprocessing as qwen3_vl_baseline.get_qwen_vl_output; per call one forward
(no generation): SIA type probabilities from the trained heads (sia_score.SIAScorer).
  completion call: p_success >= QIC_TAU_DONE -> "YES." else "NO."
  mistake call   : p_mistake >= QIC_TAU_MIS  -> "YES. <feedback>" ; feedback = retrieved from the TRAIN feedback bank
                   (QIC_FB=retrieve, default) or generated by the LM after "YES." (QIC_FB=generate, isolates content)
  --order mistake_first as in qic_prob.py. Every decision is logged to QIC_PROB_LOG.
Flags: --qic_lora DIR --sia_ckpt last.pt --bank bank.json --tau_done X --tau_mis Y --order O --fb retrieve|generate --prob_log F"""
from __future__ import annotations
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
for flag, env in (("--qic_lora", "QIC_LORA"), ("--sia_ckpt", "QIC_SIA_CKPT"), ("--bank", "QIC_BANK"), ("--tau_done", "QIC_TAU_DONE"),
                  ("--tau_mis", "QIC_TAU_MIS"), ("--order", "QIC_ORDER"), ("--fb", "QIC_FB"), ("--prob_log", "QIC_PROB_LOG")):
    if flag in sys.argv:
        k = sys.argv.index(flag); os.environ[env] = sys.argv[k + 1]; del sys.argv[k:k + 2]
import torch  # noqa: E402
import qic_lora as _w  # noqa: E402
import sia_score  # noqa: E402
baseline = _w.baseline
TAU_D = float(os.environ.get("QIC_TAU_DONE", "0.5")); TAU_M = float(os.environ.get("QIC_TAU_MIS", "0.5"))
ORDER = os.environ.get("QIC_ORDER", "done_first"); FB = os.environ.get("QIC_FB", "retrieve"); LOG = os.environ.get("QIC_PROB_LOG")
_S = {}; _pending = {"fb": None}


@torch.no_grad()
def _score_and_answer(mode, model, processor, video, instruction, max_new_tokens):
    if "s" not in _S:
        _S["s"] = sia_score.SIAScorer(model, processor, os.environ["QIC_SIA_CKPT"], os.environ["QIC_BANK"])
    text = processor.apply_chat_template(baseline.build_messages(mode, instruction=instruction), tokenize=False, add_generation_prompt=True)
    meta = [{"fps": 2, "total_num_frames": len(video)}]
    inp = processor(text=[text], images=None, videos=video, padding=True, video_metadata=meta, return_tensors="pt").to("cuda").to(torch.bfloat16)
    with torch.autocast(device_type="cuda", dtype=torch.bfloat16):
        o = model(**inp, use_cache=False, logits_to_keep=1, output_hidden_states=True)
    r = _S["s"].score(o.hidden_states)
    q, tau = (r["p_success"], TAU_D) if mode == "instruction_end" else (r["p_mistake"], TAU_M)
    yes = q >= tau; out = "NO."
    if yes and mode == "instruction_end":
        out = "YES."
    elif yes and FB == "retrieve":
        out = "YES. " + r["fb"]
    elif yes:
        inp2 = processor(text=[text + "YES."], images=None, videos=video, padding=True, video_metadata=meta, return_tensors="pt").to("cuda").to(torch.bfloat16)
        with torch.autocast(device_type="cuda", dtype=torch.bfloat16):
            g = model.generate(**inp2, max_new_tokens=max_new_tokens, do_sample=False)
        fb = processor.batch_decode([g[0][inp2.input_ids.shape[1]:]], skip_special_tokens=True, clean_up_tokenization_spaces=False)[0].strip()
        out = "YES. " + (fb or "You made a mistake.")
    if LOG:
        with open(LOG, "a") as f:
            f.write(json.dumps({"mode": mode, "instr": instruction[:80], "n": len(video), "p": round(q, 4), "tau": tau, "yes": yes,
                                "fb": r["fb"] if mode != "instruction_end" else None, "fb_sim": round(r["fb_sim"], 4)}) + "\n")
    return out


def get_output(mode, model, processor, video=None, instruction=None, max_new_tokens=128):
    if ORDER != "mistake_first":
        return _score_and_answer(mode, model, processor, video, instruction, max_new_tokens)
    if mode == "instruction_end":
        m = _score_and_answer("mistake_inference", model, processor, video, instruction, 1024)
        if m.startswith("YES"):
            _pending["fb"] = m; return "NO."
        _pending["fb"] = None
        return _score_and_answer("instruction_end", model, processor, video, instruction, max_new_tokens)
    fb, _pending["fb"] = _pending["fb"], None
    return fb or "NO."


baseline.get_qwen_vl_output = get_output
print(f"qic_sia: order={ORDER} tau_done={TAU_D} tau_mis={TAU_M} fb={FB} lora={os.environ.get('QIC_LORA')}", flush=True)
if __name__ == "__main__":
    baseline.run(baseline.parse_args())
